package io.github.hectorvent.floci.services.iam;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.github.hectorvent.floci.core.common.VendoredResources;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * What every paged IAM operation pages by, read once from the vendored
 * {@code aws/iam-paginators.json}. {@link IamQueryHandler} pages each list through one path that
 * reads its operation's entry here.
 *
 * <p>The file is generated by {@code tools/aws/regen_iam_paginators.py} from botocore's IAM model:
 * every operation whose request models {@code Marker}, with botocore's paginator where it has one.
 * An operation AWS starts paging later needs a regeneration, not new handler code. {@code make
 * aws-data-check} fails when it is stale against the pinned botocore.
 *
 * <p>A missing or malformed resource is a build defect, not a runtime condition, so loading fails
 * with {@link IllegalStateException} rather than degrading to lists that never page.
 */
final class IamPaginators {

    static final String RESOURCE_NAME = "aws/iam-paginators.json";

    /**
     * One operation's paging. {@code limitKey} is null where the request models no limit, and
     * {@code defaultItems} is null where the reference documents no default page size, in which
     * case an omitted limit returns the whole list. {@code resultKeys} is empty for an operation
     * botocore has no paginator for.
     */
    record Paginator(String inputToken, String outputToken, String limitKey, String moreResults,
                     List<String> resultKeys, int minItems, int maxItems, Integer defaultItems) {
    }

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final class Holder {
        static final Map<String, Paginator> OPERATIONS = VendoredResources.read(RESOURCE_NAME,
                "IAM paginator table", IamPaginators::parse);
    }

    private IamPaginators() {
    }

    /** The paging of {@code operation}; an operation the table lacks is a handler defect. */
    static Paginator of(String operation) {
        Paginator paginator = Holder.OPERATIONS.get(operation);
        if (paginator == null) {
            throw new IllegalStateException(RESOURCE_NAME + " has no paged operation " + operation);
        }
        return paginator;
    }

    static Map<String, Paginator> parse(InputStream in) throws IOException {
        JsonNode operations = MAPPER.readTree(in).path("operations");
        if (!operations.isObject() || operations.isEmpty()) {
            throw new IllegalStateException(RESOURCE_NAME + " carries no operations");
        }
        Map<String, Paginator> parsed = new LinkedHashMap<>();
        operations.properties().forEach(entry -> parsed.put(entry.getKey(), paginator(entry.getKey(), entry.getValue())));
        return Map.copyOf(parsed);
    }

    private static Paginator paginator(String operation, JsonNode node) {
        String limitKey = text(node, "limitKey");
        JsonNode bounds = node.path("maxItems");
        if (limitKey != null && !(bounds.path("min").isInt() && bounds.path("max").isInt())) {
            throw new IllegalStateException(RESOURCE_NAME + ": " + operation + " has a limit without bounds");
        }
        List<String> resultKeys = new ArrayList<>();
        node.path("resultKeys").forEach(key -> resultKeys.add(key.asText()));
        String inputToken = text(node, "inputToken");
        String outputToken = text(node, "outputToken");
        String moreResults = text(node, "moreResults");
        if (inputToken == null || outputToken == null || moreResults == null) {
            throw new IllegalStateException(RESOURCE_NAME + ": " + operation + " lacks a token");
        }
        return new Paginator(inputToken, outputToken, limitKey, moreResults, List.copyOf(resultKeys),
                bounds.path("min").asInt(), bounds.path("max").asInt(),
                bounds.path("default").isInt() ? bounds.path("default").asInt() : null);
    }

    private static String text(JsonNode node, String field) {
        JsonNode value = node.path(field);
        return value.isTextual() ? value.asText() : null;
    }
}
